import type { QuizCatalog } from "./buildQuizCatalog";

export const QUIZ_CATALOG_MIGRATION_PATTERN = /^\d{14}_(seed|sync)_quiz_catalog\.sql$/;

const FORM3_SEJARAH_25_KEYS = {
  "chapters-1-3": /^quiz-v2:standard:sejarah:form-3:chapter-[123]:bm:set-[ab]:difficulty-all$/,
  "chapters-4-8": /^quiz-v2:standard:sejarah:form-3:chapter-[4-8]:bm:set-[ab]:difficulty-all$/,
} as const;

function literal(value: string | number | boolean): string {
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${value.replace(/'/g, "''")}'`;
}

/** Metadata-only correction for existing active canonical quiz rows. */
export function renderForm3SejarahQuiz25MetadataSql(
  fullCatalog: QuizCatalog,
  scope: keyof typeof FORM3_SEJARAH_25_KEYS = "chapters-1-3",
): string {
  const rows = fullCatalog.quizzes.filter((quiz) => FORM3_SEJARAH_25_KEYS[scope].test(quiz.quizKey));
  const expectedRows = scope === "chapters-1-3" ? 6 : 10;
  const countWord = scope === "chapters-1-3" ? "six" : "ten";
  const chapterLabel = scope === "chapters-1-3" ? "1-3" : "4-8";
  if (rows.length !== expectedRows || rows.some((quiz) => quiz.totalQuestions !== 25)) {
    throw new Error(`Expected exactly ${countWord} 25-question Form 3 Sejarah catalog rows`);
  }
  const values = rows.map((quiz) =>
    `    (${[
      quiz.quizKey,
      quiz.totalQuestions,
      quiz.easyCount,
      quiz.mediumCount,
      quiz.hardCount,
      quiz.timerBonusAllowed,
      quiz.maxXp,
    ].map(literal).join(", ")})`,
  );
  return `-- GENERATED by scripts/generate-quiz-catalog.ts from the runtime quiz catalog.
-- Scope: active Form 3 Sejarah Chapters ${chapterLabel}, Sets A/B; metadata only.
-- Exactly ${countWord} existing active canonical rows must match before updating.
do $$
begin
  if (select count(*) from public.quiz_catalog
      where is_active and subject_id = 'sejarah' and form = 3
        and quiz_key = any (array[
${rows.map((quiz) => `        ${literal(quiz.quizKey)}`).join(",\n")}
      ]::text[])) <> ${expectedRows} then
    raise exception 'Expected ${countWord} active Form 3 Sejarah quiz catalog rows';
  end if;
end $$;

update public.quiz_catalog as catalog
set total_questions = corrected.total_questions,
    easy_count = corrected.easy_count,
    medium_count = corrected.medium_count,
    hard_count = corrected.hard_count,
    timer_bonus_allowed = corrected.timer_bonus_allowed,
    max_xp = corrected.max_xp,
    updated_at = now()
from (values
${values.join(",\n")}
) as corrected (quiz_key, total_questions, easy_count, medium_count, hard_count, timer_bonus_allowed, max_xp)
where catalog.quiz_key = corrected.quiz_key
  and catalog.is_active
  and catalog.subject_id = 'sejarah'
  and catalog.form = 3;
`;
}

/**
 * Deterministic SQL that makes public.quiz_catalog match the selected app content:
 * upserts the selected quizzes, deactivates obsolete keys in the same scope
 * (keeping awards and history), and adds legacy key mappings.
 */
export function renderQuizCatalogSql(
  fullCatalog: QuizCatalog,
  scope?: "sejarah-f3",
): string {
  const inScope = (key: string) => key.startsWith("quiz-v2:standard:sejarah:form-3:");
  const catalog = scope
    ? {
        quizzes: fullCatalog.quizzes.filter((quiz) => inScope(quiz.quizKey)),
        legacyKeys: fullCatalog.legacyKeys.filter((row) => inScope(row.quizKey)),
      }
    : fullCatalog;
  const quizRows = catalog.quizzes.map(
    (q) =>
      `  (${[
        q.quizKey,
        q.kind,
        q.formula,
        q.subjectId,
        q.form,
        q.chapterKey,
        q.lang,
        q.totalQuestions,
        q.easyCount,
        q.mediumCount,
        q.hardCount,
        q.timerBonusAllowed,
        q.maxXp,
      ]
        .map(literal)
        .join(", ")})`,
  );
  const legacyRows = catalog.legacyKeys.map(
    (row) => `  (${literal(row.legacyKey)}, ${literal(row.quizKey)})`,
  );

  return `-- GENERATED by scripts/generate-quiz-catalog.ts from app quiz content.
-- Do not edit by hand: change the content and run npm run generate:quiz-catalog.
${scope ? "-- Scope: Sejarah Form 3 only.\n" : ""}-- ${catalog.quizzes.length} quizzes, ${catalog.legacyKeys.length} legacy key mappings.

insert into public.quiz_catalog (
  quiz_key, kind, formula, subject_id, form, chapter_key, lang,
  total_questions, easy_count, medium_count, hard_count,
  timer_bonus_allowed, max_xp
) values
${quizRows.join(",\n")}
on conflict (quiz_key) do update set
  kind = excluded.kind,
  formula = excluded.formula,
  subject_id = excluded.subject_id,
  form = excluded.form,
  chapter_key = excluded.chapter_key,
  lang = excluded.lang,
  total_questions = excluded.total_questions,
  easy_count = excluded.easy_count,
  medium_count = excluded.medium_count,
  hard_count = excluded.hard_count,
  timer_bonus_allowed = excluded.timer_bonus_allowed,
  max_xp = excluded.max_xp,
  is_active = true,
  updated_at = now();

update public.quiz_catalog
set is_active = false, updated_at = now()
where is_active
${scope ? "  and subject_id = 'sejarah' and form = 3\n" : ""}  and quiz_key <> all (array[
${catalog.quizzes.map((q) => `    ${literal(q.quizKey)}`).join(",\n")}
  ]::text[]);

insert into public.quiz_catalog_legacy_keys (legacy_key, quiz_key) values
${legacyRows.join(",\n")}
on conflict (legacy_key, quiz_key) do nothing;
`;
}
