// Generates a tiny static summary of curriculum-registry stats.
//
// Two consumers rely on this generated module:
//  1. The admin Reports server function (-reports.server.ts) needs global
//     aggregate counts (CONTENT_STATS).
//  2. Subject cards on /notes, /mindmaps, /quizzes, /flashcards need
//     per-subject/per-form chapter counts (SUBJECT_FORM_SUMMARY) available
//     synchronously on first render — they previously waited on a
//     client-only dynamic import of the full multi-MB curriculum registry,
//     so the very first paint always showed "0 Forms" until that import
//     resolved.
//
// Why this exists: -reports.server.ts (and, before this change, the subject
// card components) previously dynamically imported the full curriculum
// registry (../content/registry, ../data/content — several MB of every
// subject/chapter's notes/quizzes/flashcards/mindmaps). That's a genuine
// server-side code path for Reports (it runs whenever an admin opens
// Reports), so it can't just defer to a browser-only dynamic import: Vite's
// SSR build must keep the registry physically bundled into the deployed
// Cloudflare Worker for that handler to work, which alone accounts for
// several MB of the Worker's compressed size limit. The subject cards don't
// even have that excuse — they just need a handful of small counts.
//
// This script runs once at build time (from a Node context, not the
// deployed Worker or the client bundle), computes those counts from the
// real registry, and writes them to a generated module small enough to
// import statically and safely from both SSR and client entry points.
// Re-run automatically by `npm run build` before `vite build`, so the
// numbers always reflect the content being deployed.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { chapters, getSubjectFormStats, type FormStat } from "../src/content/registry";
import { getChapterFeatures } from "../src/content/types";
import { subjects } from "../src/data/subjects-meta";

const __dirname = dirname(fileURLToPath(import.meta.url));

let publishedNotes = 0;
let publishedQuizzes = 0;
let publishedFlashcards = 0;
let publishedMindmaps = 0;
let missingContent = 0;

for (const chapter of chapters) {
  const features = getChapterFeatures(chapter);
  if (features.notes) publishedNotes += 1;
  if (features.quiz) publishedQuizzes += 1;
  if (features.flashcards) publishedFlashcards += 1;
  if (features.mindMap) publishedMindmaps += 1;
  if (!(features.notes && features.quiz && features.flashcards && features.mindMap)) {
    missingContent += 1;
  }
}

// Per-subject/per-form chapter counts only — deliberately excludes any real
// notes/quiz/flashcard/mindmap content so this stays a "small counts" module,
// not a second copy of the registry.
type FormSummary = { form: FormStat["form"]; chapterCount: number };
const subjectFormSummary: Record<string, FormSummary[]> = {};
for (const subject of subjects) {
  subjectFormSummary[subject.id] = getSubjectFormStats(subject.id).map((stat) => ({
    form: stat.form,
    chapterCount: stat.chapterCount,
  }));
}

const outPath = resolve(__dirname, "../src/lib/content-stats.generated.ts");
const contents = `// AUTO-GENERATED by scripts/generate-content-stats.ts — do not edit by hand.
// Regenerated automatically by \`npm run build\`. See that script for why this
// exists (keeps the admin Reports server function and the subject card
// components out of the curriculum registry's bundle weight, while still
// giving both real, non-zero counts on first render).
export const CONTENT_STATS = {
  totalSubjects: ${subjects.length},
  totalChapters: ${chapters.length},
  publishedNotes: ${publishedNotes},
  publishedQuizzes: ${publishedQuizzes},
  publishedFlashcards: ${publishedFlashcards},
  publishedMindmaps: ${publishedMindmaps},
  missingContent: ${missingContent},
} as const;

export type SubjectFormSummary = { form: ${JSON.stringify(["Form 1", "Form 2", "Form 3"]).replace(/"/g, "").split(",").map((f) => `"${f}"`).join(" | ")}; chapterCount: number };

// Per-subject Form 1/2/3 chapter counts, safe to import synchronously during
// SSR/initial render (unlike @/content/registry's getSubjectFormStats, which
// pulls in the full multi-MB curriculum registry).
export const SUBJECT_FORM_SUMMARY: Record<string, SubjectFormSummary[]> = ${JSON.stringify(
  subjectFormSummary,
  null,
  2,
)};
`;

writeFileSync(outPath, contents, "utf8");
console.log(
  `[generate-content-stats] wrote ${outPath} (subjects=${subjects.length}, chapters=${chapters.length}, missing=${missingContent})`,
);
