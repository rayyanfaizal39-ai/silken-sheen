// Generates a tiny static summary of curriculum-registry stats for the admin
// Reports page (src/routes/-reports.server.ts).
//
// Why this exists: -reports.server.ts previously dynamically imported the
// full curriculum registry (../content/registry, ../data/content — several
// MB of every subject/chapter's notes/quizzes/flashcards/mindmaps) inside its
// createServerFn handler. That's a genuine server-side code path (it runs
// whenever an admin opens Reports), so — unlike the client-only UI
// components — it can't just defer to a browser-only dynamic import: Vite's
// SSR build must keep the registry physically bundled into the deployed
// Cloudflare Worker for that handler to work, which alone accounts for
// several MB of the Worker's compressed size limit.
//
// The handler only ever needed a handful of aggregate counts, not the actual
// note/quiz/flashcard content. This script runs once at build time (from a
// Node context, not the deployed Worker), computes those counts from the
// real registry, and writes them to a generated module small enough to
// import statically and safely. Re-run automatically by `npm run build`
// before `vite build`, so the numbers always reflect the content being
// deployed.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { chapters } from "../src/content/registry";
import { getChapterFeatures } from "../src/content/types";
import { subjects } from "../src/data/subjects-meta";

const __dirname = dirname(fileURLToPath(import.meta.url));

let publishedNotes = 0;
let publishedQuizzes = 0;
let publishedFlashcards = 0;
let publishedMindmaps = 0;
let missingContent = 0;

for (const chapter of chapters) {
  const features = getChapterFeatures(chapter);
  if (features.notes) publishedNotes += 1;
  if (features.quiz) publishedQuizzes += 1;
  if (features.flashcards) publishedFlashcards += 1;
  if (features.mindMap) publishedMindmaps += 1;
  if (!(features.notes && features.quiz && features.flashcards && features.mindMap)) {
    missingContent += 1;
  }
}

const outPath = resolve(__dirname, "../src/lib/content-stats.generated.ts");
const contents = `// AUTO-GENERATED by scripts/generate-content-stats.ts — do not edit by hand.
// Regenerated automatically by \`npm run build\`. See that script for why this
// exists (keeps the admin Reports server function out of the curriculum
// registry's SSR bundle weight).
export const CONTENT_STATS = {
  totalSubjects: ${subjects.length},
  totalChapters: ${chapters.length},
  publishedNotes: ${publishedNotes},
  publishedQuizzes: ${publishedQuizzes},
  publishedFlashcards: ${publishedFlashcards},
  publishedMindmaps: ${publishedMindmaps},
  missingContent: ${missingContent},
} as const;
`;

writeFileSync(outPath, contents, "utf8");
console.log(
  `[generate-content-stats] wrote ${outPath} (subjects=${subjects.length}, chapters=${chapters.length}, missing=${missingContent})`,
);
